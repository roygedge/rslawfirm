/**
 * Search FAQs by keyword
 */
function rslawfirm_search_faqs($keyword, $area = '') {
    $all_faqs = rslawfirm_get_all_faqs();
    $results = [];
    
    $search_areas = empty($area) ? array_keys($all_faqs) : [$area];
    
    foreach ($search_areas as $search_area) {
        if (!isset($all_faqs[$search_area])) continue;
        
        foreach ($all_faqs[$search_area] as $faq) {
            $searchable_text = $faq['question'] . ' ' . $faq['answer'] . ' ' . implode(' ', $faq['keywords']);
            
            if (stripos($searchable_text, $keyword) !== false) {
                $faq['area'] = $search_area;
                $results[] = $faq;
            }
        }
    }
    
    return $results;
}

/**
 * Get random FAQs for homepage or sidebar
 */
function rslawfirm_get_random_faqs($count = 5) {
    $all_faqs = rslawfirm_get_all_faqs();
    $combined = [];
    
    foreach ($all_faqs as $area => $faqs) {
        foreach ($faqs as $faq) {
            $faq['area'] = $area;
            $combined[] = $faq;
        }
    }
    
    shuffle($combined);
    return array_slice($combined, 0, $count);
}

