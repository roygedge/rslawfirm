/**
 * Generate FAQ schema markup
 */
function rslawfirm_generate_faq_schema($faqs) {
    $faq_items = [];
    
    foreach ($faqs as $faq) {
        $faq_items[] = [
            '@type' => 'Question',
            'name' => $faq['question'],
            'acceptedAnswer' => [
                '@type' => 'Answer',
                'text' => $faq['answer']
            ]
        ];
    }
    
    if (empty($faq_items)) {
        return '';
    }
    
    $schema = [
        '@context' => 'https://schema.org',
        '@type' => 'FAQPage',
        'mainEntity' => $faq_items
    ];
    
    return '<script type="application/ld+json">' . wp_json_encode($schema, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) . '</script>';
}

/**
 * Display FAQ section HTML
 */
function rslawfirm_display_faq_section($faqs, $title = 'שאלות נפוצות') {
    if (empty($faqs)) {
        return '';
    }
    
    ob_start();
    ?>
    <section class="faq-section">
        <h2><?php echo esc_html($title); ?></h2>
        
        <?php foreach ($faqs as $faq): ?>
        <details>
            <summary><?php echo esc_html($faq['question']); ?></summary>
            <p><?php echo esc_html($faq['answer']); ?></p>
        </details>
        <?php endforeach; ?>
    </section>
    
    <?php echo rslawfirm_generate_faq_schema($faqs); ?>
    <?php
    
    return ob_get_clean();
}

/**
 * Add FAQ shortcode
 */
function rslawfirm_faq_shortcode($atts) {
    $atts = shortcode_atts([
        'area' => 'general',
        'count' => 0,
        'title' => 'שאלות נפוצות'
    ], $atts);
    
    if ($atts['area'] === 'random') {
        $faqs = rslawfirm_get_random_faqs($atts['count'] ?: 5);
    } else {
        $faqs = rslawfirm_get_faqs_by_area($atts['area']);
        if ($atts['count'] > 0) {
            $faqs = array_slice($faqs, 0, $atts['count']);
        }
    }
    
    return rslawfirm_display_faq_section($faqs, $atts['title']);
}
add_shortcode('rslawfirm_faq', 'rslawfirm_faq_shortcode');

/**
 * AJAX handler for FAQ search
 */
function rslawfirm_ajax_search_faqs() {
    check_ajax_referer('rslawfirm_nonce', 'nonce');
    
    $keyword = sanitize_text_field($_POST['keyword']);
    $area = sanitize_text_field($_POST['area']);
    
    $results = rslawfirm_search_faqs($keyword, $area);
    
    wp_send_json_success([
        'results' => $results,
        'count' => count($results)
    ]);
}
add_action('wp_ajax_search_faqs', 'rslawfirm_ajax_search_faqs');
add_action('wp_ajax_nopriv_search_faqs', 'rslawfirm_ajax_search_faqs');
